/// Generate Cargo.toml for the dispatcher WASM component project.
pub fn generate_cargo_toml(manifest: &ExtensionManifest) -> String {
    let ctx = CodegenContext::new(manifest);
    let mut toml = String::new();

    toml.push_str(&format!(
        "# Auto-generated by wawk-codegen — DO NOT EDIT\n\
         # Product: {} v{}\n\n\
         [package]\n\
         name = \"wawk-{}-dispatcher\"\n\
         version = \"{}\"\n\
         edition = \"2021\"\n\n\
         [lib]\n\
         crate-type = [\"cdylib\"]\n\n\
         [dependencies]\n\
         wit-bindgen = \"0.42\"\n\
         wit-bindgen-rt = \"0.42\"\n\n\
         [package.metadata.component]\n\
         package = \"wawk:{}\"\n\n\
         [package.metadata.component.target]\n\
         path = \"wit\"\n\
         world = \"{}-dispatcher\"\n\n\
         [package.metadata.component.target.dependencies]\n\
         \"wawk:extensions\" = {{ path = \"wit/deps/extensions\" }}\n\
         \"wawk:services\" = {{ path = \"wit/deps/services\" }}\n\n\
         [profile.release]\n\
         opt-level = \"s\"\n\
         lto = true\n",
        ctx.product_name, manifest.version,
        ctx.product_name, manifest.version,
        ctx.product_name, ctx.product_name
    ));

    toml
}

/// Generate lib.rs that includes the wit-bindgen generate macro and the dispatcher module.
pub fn generate_lib_rs(manifest: &ExtensionManifest) -> String {
    let ctx = CodegenContext::new(manifest);
    let mut rs = String::new();

    rs.push_str(&format!(
        "//! Auto-generated dispatcher lib for {} v{}.\n\
         //! DO NOT EDIT — generated by wawk-codegen.\n\n",
        ctx.product_name, manifest.version
    ));

    // wit-bindgen generate at crate root
    rs.push_str(&format!(
        "wit_bindgen::generate!({{\n    world: \"{}-dispatcher\",\n    path: \"wit\",\n    with: {{\n",
        ctx.product_name
    ));
    rs.push_str("        \"wawk:services/host-services\": generate,\n");
    for extension in &manifest.extensions {
        rs.push_str(&format!(
            "        \"wawk:extensions/{}\": generate,\n",
            extension.interface
        ));
        if extension.format {
            let format_iface = extension.interface.replace("-functions", "-format");
            rs.push_str(&format!(
                "        \"wawk:extensions/{}\": generate,\n",
                format_iface
            ));
        }
    }
    rs.push_str("    },\n});\n\n");

    rs.push_str("#[allow(unused_imports)]\nmod bindings;\n\n");
    rs.push_str("mod dispatcher;\n");
    rs.push_str(&format!(
        "use dispatcher::{}Dispatcher;\n\n",
        to_pascal(&ctx.product_name)
    ));

    // Export macro must be in the same module as wit_bindgen::generate!
    rs.push_str(&format!(
        "bindings::export!({}Dispatcher with_types_in bindings);\n",
        to_pascal(&ctx.product_name)
    ));

    rs
}

/// Generate the wawk:extensions dependency WIT file containing all extension interfaces
/// needed by this dispatcher.
pub fn generate_extensions_deps_wit(manifest: &ExtensionManifest) -> String {
    let mut wit = String::new();
    wit.push_str("/// Auto-generated extension interface definitions.\n");
    wit.push_str("/// DO NOT EDIT — generated by wawk-codegen.\n\n");
    wit.push_str("package wawk:extensions;\n\n");

    for extension in &manifest.extensions {
        // Functions interface
        wit.push_str(&format!(
            "interface {} {{\n    call: func(name: string, args: list<string>) -> option<string>;\n}}\n\n",
            extension.interface
        ));

        // Format interface (if applicable)
        if extension.format {
            let format_iface = extension.interface.replace("-functions", "-format");
            wit.push_str(&format!(
                "interface {} {{\n    detect: func(input: string) -> string;\n    parse: func(input: string) -> string;\n    serialize: func(tree-json: string) -> string;\n}}\n\n",
                format_iface
            ));
        }
    }

    wit
}

/// Generate the wawk:services dependency WIT file (host-services interface).
pub fn generate_services_deps_wit() -> String {
    "/// Auto-generated host-services interface.\n\
     /// DO NOT EDIT — generated by wawk-codegen.\n\n\
     package wawk:services;\n\n\
     interface host-services {\n\
         notify: func(event-type: string, payload: string) -> result<string, string>;\n\
         store-set: func(key: string, value: string) -> result<_, string>;\n\
         store-get: func(key: string) -> result<string, string>;\n\
         log: func(level: string, message: string);\n\
     }\n"
        .to_string()
}

