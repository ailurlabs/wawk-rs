/// Write generated dispatcher files to the output directory.
///
/// Creates:
/// - `<output_dir>/Cargo.toml` — dispatcher component project
/// - `<output_dir>/src/lib.rs` — crate root (includes dispatcher module)
/// - `<output_dir>/src/dispatcher.rs` — the Rust implementation
/// - `<output_dir>/wit/dispatcher.wit` — the dispatcher world
pub fn write_dispatcher(manifest: &ExtensionManifest, output_dir: &Path) -> Result<()> {
    let wit_dir = output_dir.join("wit");
    let src_dir = output_dir.join("src");

    fs::create_dir_all(&wit_dir)
        .with_context(|| format!("failed to create wit dir: {}", wit_dir.display()))?;
    fs::create_dir_all(&src_dir)
        .with_context(|| format!("failed to create src dir: {}", src_dir.display()))?;

    // Cargo.toml
    let cargo_content = generate_cargo_toml(manifest);
    let cargo_path = output_dir.join("Cargo.toml");
    fs::write(&cargo_path, &cargo_content)
        .with_context(|| format!("failed to write {}", cargo_path.display()))?;

    // lib.rs
    let lib_content = generate_lib_rs(manifest);
    let lib_path = src_dir.join("lib.rs");
    fs::write(&lib_path, &lib_content)
        .with_context(|| format!("failed to write {}", lib_path.display()))?;

    // dispatcher.wit
    let wit_content = generate_dispatcher_wit(manifest);
    let wit_path = wit_dir.join("dispatcher.wit");
    fs::write(&wit_path, &wit_content)
        .with_context(|| format!("failed to write {}", wit_path.display()))?;

    // dispatcher.rs
    let rs_content = generate_dispatcher_rs(manifest);
    let rs_path = src_dir.join("dispatcher.rs");
    fs::write(&rs_path, &rs_content)
        .with_context(|| format!("failed to write {}", rs_path.display()))?;

    // WIT deps: extensions package (interface definitions for each extension)
    let deps_extensions_dir = wit_dir.join("deps").join("extensions");
    fs::create_dir_all(&deps_extensions_dir)
        .with_context(|| format!("failed to create {}", deps_extensions_dir.display()))?;
    let extensions_deps = generate_extensions_deps_wit(manifest);
    let extensions_deps_path = deps_extensions_dir.join("world.wit");
    fs::write(&extensions_deps_path, &extensions_deps)
        .with_context(|| format!("failed to write {}", extensions_deps_path.display()))?;

    // WIT deps: services package (host-services interface)
    let deps_services_dir = wit_dir.join("deps").join("services");
    fs::create_dir_all(&deps_services_dir)
        .with_context(|| format!("failed to create {}", deps_services_dir.display()))?;
    let services_deps = generate_services_deps_wit();
    let services_deps_path = deps_services_dir.join("host-services.wit");
    fs::write(&services_deps_path, &services_deps)
        .with_context(|| format!("failed to write {}", services_deps_path.display()))?;

    Ok(())
}

