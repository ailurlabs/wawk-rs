//! wawk-codegen: Dispatcher code generation tool.
//!
//! Reads a `extension-manifest.json` and generates:
//! - `dispatcher.wit`: WIT world importing all extension interfaces + host-services,
//!   exporting a unified `host-functions` dispatch interface.
//! - `dispatcher.rs`: Rust source implementing namespace-based routing
//!   from the unified dispatch to each extension's `call()` function.
//!
//! # Usage
//!
//! ```bash
//! wawk-codegen <manifest-path> <output-dir>
//! ```

use anyhow::{Context, Result};
use serde::Deserialize;
use std::fs;
use std::path::Path;

// ---------------------------------------------------------------------------
// Manifest types
// ---------------------------------------------------------------------------

/// Top-level extension manifest (extension-manifest.json).
#[derive(Debug, Deserialize, Clone)]
pub struct ExtensionManifest {
    /// Product name (e.g. "product-a").
    pub name: String,
    /// Product version.
    pub version: String,
    /// Optional product description.
    #[serde(default)]
    pub description: String,
    /// List of extension dependencies.
    pub extensions: Vec<ExtensionEntry>,
    /// Host services configuration.
    #[serde(default)]
    pub host_services: Option<HostServicesConfig>,
}

/// A single extension dependency entry.
#[derive(Debug, Deserialize, Clone)]
pub struct ExtensionEntry {
    /// Extension name (e.g. "product-a", "extension-1", "extension-2", "extension-3").
    pub name: String,
    /// WIT interface name (e.g. "product-a-functions").
    pub interface: String,
    /// Whether this extension also exports a format interface.
    #[serde(default)]
    pub format: bool,
    /// Optional description.
    #[serde(default)]
    pub description: String,
}

/// Host services configuration.
#[derive(Debug, Deserialize, Clone)]
pub struct HostServicesConfig {
    #[serde(default)]
    pub notify: String,
    #[serde(default)]
    pub store_set: String,
    #[serde(default)]
    pub store_get: String,
    #[serde(default)]
    pub log: String,
}

// ---------------------------------------------------------------------------
// Manifest loading
// ---------------------------------------------------------------------------

/// Load and parse a extension-manifest.json file.
pub fn load_manifest(path: &Path) -> Result<ExtensionManifest> {
    let content = fs::read_to_string(path)
        .with_context(|| format!("failed to read manifest: {}", path.display()))?;
    let manifest: ExtensionManifest = serde_json::from_str(&content)
        .with_context(|| format!("failed to parse manifest: {}", path.display()))?;
    Ok(manifest)
}

// ---------------------------------------------------------------------------
// Code generation context
// ---------------------------------------------------------------------------

/// Internal context used during code generation.
struct CodegenContext {
    /// Product name in kebab-case (e.g. "product-a").
    product_name: String,
    /// Product name in snake_case (e.g. "product_a").
    product_snake: String,
}

impl CodegenContext {
    fn new(manifest: &ExtensionManifest) -> Self {
        Self {
            product_name: manifest.name.clone(),
            product_snake: manifest.name.replace('-', "_"),
        }
    }
}

/// Convert kebab-case to snake_case.
pub fn to_snake(s: &str) -> String {
    s.replace('-', "_")
}

// ---------------------------------------------------------------------------
// WIT generation
// ---------------------------------------------------------------------------

/// Generate the dispatcher WIT world source.
///
/// The generated world:
/// - Imports each extension's functions interface (and format interface if applicable)
/// - Imports host-services for platform callbacks
/// - Exports a unified `host-functions` interface for the MCP server to call
pub fn generate_dispatcher_wit(manifest: &ExtensionManifest) -> String {
    let ctx = CodegenContext::new(manifest);
    let mut wit = String::new();

    // Header
    wit.push_str(&format!(
        "/// Auto-generated dispatcher WIT for {} v{}.\n\
         /// DO NOT EDIT — generated by wawk-codegen.\n\
         ///\n\
         /// This world imports all extension interfaces and exports a unified\n\
         /// host-functions dispatch interface for the MCP server.\n\n\
         package wawk:{};\n\n",
        ctx.product_name, manifest.version, ctx.product_name
    ));

    // World definition
    wit.push_str(&format!("world {}-dispatcher {{\n", ctx.product_name));

    // Import host-services
    wit.push_str("    // Host platform services (notify, store, log).\n");
    wit.push_str("    import wawk:services/host-services;\n\n");

    // Import each extension's interfaces
    wit.push_str("    // Extension function interfaces.\n");
    for extension in &manifest.extensions {
        wit.push_str(&format!(
            "    import wawk:extensions/{};\n",
            extension.interface
        ));
    }
    wit.push('\n');

    // Import format interfaces for extensions that have them
    let format_extensions: Vec<_> = manifest.extensions.iter().filter(|p| p.format).collect();
    if !format_extensions.is_empty() {
        wit.push_str("    // Extension format interfaces.\n");
        for extension in &format_extensions {
            let format_iface = extension.interface.replace("-functions", "-format");
            wit.push_str(&format!("    import wawk:extensions/{};\n", format_iface));
        }
        wit.push('\n');
    }

    // Export unified host-functions interface
    wit.push_str("    // Unified dispatch interface exported to the MCP server.\n");
    wit.push_str("    export host-functions;\n");
    wit.push_str("}\n\n");

    // Host-functions interface definition
    wit.push_str("/// Unified dispatch interface.\n");
    wit.push_str("/// The MCP server calls `call()` with a fully-qualified tool name.\n");
    wit.push_str("/// The dispatcher routes to the correct extension based on namespace prefix.\n");
    wit.push_str("interface host-functions {\n");
    wit.push_str("    /// Dispatch a tool call to the appropriate extension.\n");
    wit.push_str("    /// `name` is namespace-qualified (e.g. \"product-a.lookup\").\n");
    wit.push_str("    /// `args` are JSON-encoded arguments.\n");
    wit.push_str("    /// Returns the extension's JSON response, or none if no extension handled it.\n");
    wit.push_str("    call: func(name: string, args: list<string>) -> option<string>;\n");
    wit.push_str("}\n");

    wit
}

// ---------------------------------------------------------------------------
// Rust source generation
// ---------------------------------------------------------------------------

/// Generate the dispatcher Rust source code (dispatcher.rs module).
///
/// The generated source:
/// - Implements the `host-functions` export with namespace-based routing
/// - Each extension gets a match arm that strips the namespace prefix and delegates
/// - Uses `crate::bindings::` to reference wit-bindgen generated types from lib.rs
pub fn generate_dispatcher_rs(manifest: &ExtensionManifest) -> String {
    let ctx = CodegenContext::new(manifest);
    let mut rs = String::new();

    // File header
    rs.push_str(&format!(
        "//! Auto-generated dispatcher for {} v{}.\n\
         //! DO NOT EDIT — generated by wawk-codegen.\n\
         //!\n\
         //! Routes incoming tool calls to the appropriate extension based on\n\
         //! namespace prefix (e.g. \"product-a.lookup\" → product extension).\n\n",
        ctx.product_name, manifest.version
    ));

    // Import the export macro from crate-level bindings (not used here, export is in lib.rs)
    // The dispatcher module only contains the Guest trait implementation.

    // Component struct
    rs.push_str(&format!(
        "pub(crate) struct {}Dispatcher;\n\n",
        to_pascal(&ctx.product_name)
    ));

    // Implement Guest trait for host-functions export
    let host_fn_module = format!(
        "crate::bindings::exports::wawk::{}::host_functions",
        ctx.product_snake
    );
    rs.push_str(&format!(
        "impl {}::Guest for {}Dispatcher {{\n",
        host_fn_module,
        to_pascal(&ctx.product_name)
    ));
    rs.push_str(
        "    fn call(name: String, args: Vec<String>) -> Option<String> {\n\
         \x20       // Extract namespace prefix (everything before the first '.').\n\
         \x20       let (namespace, func_name) = match name.find('.') {\n\
         \x20           Some(pos) => (&name[..pos], &name[pos + 1..]),\n\
         \x20           None => return None,\n\
         \x20       };\n\n\
         \x20       match namespace {\n",
    );

    // Match arms for each extension
    for extension in &manifest.extensions {
        let call_module = format!(
            "crate::bindings::wawk::extensions::{}",
            extension.interface.replace('-', "_")
        );
        rs.push_str(&format!(
            "            \"{}\" => {{\n\
             \x20               eprintln!(\n\
             \x20                   \"[dispatcher] routing {{}}.{{}} to extension {}\",\n\
             \x20                   namespace, func_name\n\
             \x20               );\n\
             \x20               {}::call(func_name, &args)\n\
             \x20           }}\n",
            extension.name, extension.name, call_module
        ));
    }

    // Unknown namespace fallback
    rs.push_str(
        "            _ => {\n\
         \x20               eprintln!(\"[dispatcher] unknown namespace: {}\", namespace);\n\
         \x20               None\n\
         \x20           }\n",
    );

    rs.push_str("        }\n    }\n}\n");

    rs
}

/// Convert kebab-case to PascalCase.
fn to_pascal(s: &str) -> String {
    s.split('-')
        .map(|word| {
            let mut chars = word.chars();
            match chars.next() {
                None => String::new(),
                Some(c) => {
                    let mut result = c.to_uppercase().to_string();
                    result.extend(chars);
                    result
                }
            }
        })
        .collect()
}

